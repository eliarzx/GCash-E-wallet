    // Load and fetches the data from the database to add to the JTable
    
    private void loadAccsData() {
    DefaultTableModel model = new DefaultTableModel();
    model.setColumnIdentifiers(new String[] {
        "Transaction ID", "User ID", "Amount", "Type", "Date"
    });

    try (Connection conn = DBConnection.getConnection();
         Statement stmt = conn.createStatement();
         ResultSet rs = stmt.executeQuery("SELECT AccountID, CustomerID, PhoneNumber, MPIN, Balance FROM Account")) {

        while (rs.next()) {
            model.addRow(new Object[] {
                rs.getInt("AccountID"),
                rs.getInt("CustomerID"),
                rs.getString("PhoneNumber"),
                rs.getInt("MPIN"),
                rs.getDouble("Balance")
            });
        }

        accsTable.setModel(model);

    } catch (SQLException e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error loading data: " + e.getMessage());
    }
}


