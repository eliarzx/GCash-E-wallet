    private void Apply_ButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Apply_ButtonActionPerformed
        int accountId = Session.getInstance().getAccountID();

    java.sql.Connection conn = null;
    java.sql.PreparedStatement stmt = null;
    java.sql.ResultSet rs = null;

    try {
        conn = DriverManager.getConnection(
            "jdbc:sqlserver://localhost:1433;databaseName=BankDB;encrypt=true;trustServerCertificate=true;",
            "YOUR_DB_USERNAME", "YOUR_DB_PASSWORD");

        // Check if a loan record exists for this account
        String query = "SELECT * FROM Loan WHERE AccountID = ?";
        stmt = conn.prepareStatement(query);
        stmt.setInt(1, accountId);
        rs = stmt.executeQuery();

        if (rs.next()) {
            // Loan record found
            GcashDialog dialog = new GcashDialog(null, null, 0, "You already have an outstanding loan.", 20, "Okay", null);
        } else {
            // No loan, proceed
            LoanDetails nextWindow = new LoanDetails();
            nextWindow.setVisible(true);
            this.dispose();
        }

    } catch (SQLException ex) {
        ex.printStackTrace();
        GcashDialog dialog = new GcashDialog(null, null, 0, "Database error: " + ex.getMessage(), 18, "Okay", null);
    } finally {
        try {
            if (rs != null) rs.close();
            if (stmt != null) stmt.close();
            if (conn != null) conn.close();
        } catch (SQLException e) {
            e.printStackTrace();
        }
    }
    }//GEN-LAST:event_Apply_ButtonActionPerformed

